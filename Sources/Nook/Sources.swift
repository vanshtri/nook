import AppKit

/// Watches the general pasteboard. macOS has no change notification for it, so this
/// checks a single integer twice a second (with timer tolerance so the OS can coalesce wakeups).
final class ClipboardWatcher {
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    // Password managers mark secrets with these (nspasteboard.org convention).
    private let skipTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    func start() {
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.tick() }
        t.tolerance = 0.3
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func tick() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard pb.changeCount != Store.shared.ownChangeCount else { return }

        let types = Set(pb.types ?? [])
        guard types.isDisjoint(with: skipTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.localizedName

        // Copied files (Finder) carry an icon image too; ignore those.
        if types.contains(.fileURL) { return }

        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            Store.shared.addText(s, source: source)
            return
        }
        // A bare PNG/TIFF with nothing else is what the system screenshot tool produces.
        // For a ⌘⌘ capture, use the app that was in front when you double-tapped.
        let imageSource = Capture.consumePendingApp() ?? source

        if types.contains(.png), let data = pb.data(forType: .png) {
            Store.shared.addImage(pngData: data, source: imageSource)
        } else if types.contains(.tiff), let data = pb.data(forType: .tiff),
                  let rep = NSBitmapImageRep(data: data),
                  let png = rep.representation(using: .png, properties: [:]) {
            Store.shared.addImage(pngData: png, source: imageSource)
        }
    }
}

/// Picks up screenshots taken with the system shortcuts (⌘⇧3 / ⌘⇧4 / ⌘⇧5) via Spotlight,
/// which tags them with kMDItemIsScreenCapture. Event-driven: no folder polling.
final class ScreenshotWatcher: NSObject {
    private let query = NSMetadataQuery()
    private var seen = Set<String>()

    func start() {
        query.predicate = NSPredicate(format: "kMDItemIsScreenCapture = 1")
        query.searchScopes = [NSMetadataQueryUserHomeScope]
        let nc = NotificationCenter.default
        nc.addObserver(self, selector: #selector(gathered), name: .NSMetadataQueryDidFinishGathering, object: query)
        nc.addObserver(self, selector: #selector(updated(_:)), name: .NSMetadataQueryDidUpdate, object: query)
        query.start()
    }

    /// Existing screenshots are only remembered as "seen" so we don't import your whole history.
    @objc private func gathered() {
        query.disableUpdates()
        for case let item as NSMetadataItem in query.results {
            if let path = item.value(forAttribute: NSMetadataItemPathKey) as? String { seen.insert(path) }
        }
        query.enableUpdates()
    }

    @objc private func updated(_ note: Notification) {
        let added = note.userInfo?[NSMetadataQueryUpdateAddedItemsKey] as? [NSMetadataItem] ?? []
        for item in added {
            guard let path = item.value(forAttribute: NSMetadataItemPathKey) as? String,
                  !seen.contains(path),
                  !path.hasPrefix(Store.shared.root.path) else { continue }
            seen.insert(path)
            Store.shared.addImage(at: URL(fileURLWithPath: path), move: false, source: NSWorkspace.shared.frontmostApplication?.localizedName)
        }
    }
}

/// Area capture. Opens the built-in macOS screenshot crosshair by sending ⌘⇧⌃4
/// ("capture area to clipboard"); the clipboard watcher then saves it.
/// Because macOS itself takes the picture, Nook needs no Screen Recording permission.
enum Capture {
    private static var pendingUntil = Date.distantPast
    private static var pendingApp: String?

    /// The app captured at double-tap time, returned once for the next image that lands.
    static func consumePendingApp() -> String? {
        defer { pendingUntil = .distantPast; pendingApp = nil }
        return Date() < pendingUntil ? pendingApp : nil
    }

    static func region() {
        debugLog("capture: posting cmd-shift-ctrl-4, trusted=\(AXIsProcessTrusted())")
        pendingUntil = Date().addingTimeInterval(60)
        pendingApp = NSWorkspace.shared.frontmostApplication?.localizedName
        let src = CGEventSource(stateID: .hidSystemState)
        let four: CGKeyCode = 21
        let flags: CGEventFlags = [.maskCommand, .maskShift, .maskControl]
        for keyDown in [true, false] {
            let e = CGEvent(keyboardEventSource: src, virtualKey: four, keyDown: keyDown)
            e?.flags = flags
            e?.post(tap: .cghidEventTap)
        }
    }
}

/// Detects a double tap of the left or right ⌘ key on its own (no other keys involved).
/// keyCode 55 = left ⌘, 54 = right ⌘. Needs Accessibility permission for the global monitor.
final class DoubleTapDetector {
    var onLeft: () -> Void = {}
    var onRight: () -> Void = {}

    private var downCode: UInt16?
    private var downTime: TimeInterval = 0
    private var lastTap: (code: UInt16, time: TimeInterval)?
    private let maxHold: TimeInterval = 0.3
    private let maxGap: TimeInterval = 0.4

    func start() {
        NSEvent.addGlobalMonitorForEvents(matching: [.flagsChanged, .keyDown]) { [weak self] e in self?.handle(e) }
        NSEvent.addLocalMonitorForEvents(matching: [.flagsChanged, .keyDown]) { [weak self] e in self?.handle(e); return e }
    }

    private func handle(_ e: NSEvent) {
        if e.type == .flagsChanged && (e.keyCode == 54 || e.keyCode == 55) {
            debugLog("cmd event key=\(e.keyCode) cmdDown=\(e.modifierFlags.contains(.command))")
        }
        if e.type == .keyDown { reset(); return }   // ⌘+key shortcut, not a tap
        let code = e.keyCode
        guard code == 54 || code == 55 else { reset(); return }

        let flags = e.modifierFlags.intersection(.deviceIndependentFlagsMask)
        let others: NSEvent.ModifierFlags = [.shift, .option, .control, .function, .capsLock]

        if flags.contains(.command) {
            if !flags.intersection(others).isEmpty || downCode != nil { reset(); return }
            downCode = code
            downTime = e.timestamp
        } else if downCode == code {
            downCode = nil
            guard e.timestamp - downTime <= maxHold else { lastTap = nil; return }
            if let last = lastTap, last.code == code, e.timestamp - last.time <= maxGap {
                lastTap = nil
                debugLog("DOUBLE TAP \(code == 55 ? "left" : "right")")
                code == 55 ? onLeft() : onRight()
            } else {
                lastTap = (code, e.timestamp)
            }
        }
    }

    private func reset() {
        downCode = nil
        lastTap = nil
    }
}

/// Appends a line to ~/Library/Application Support/Nook/debug.log (for troubleshooting).
func debugLog(_ msg: String) {
    let url = Store.shared.root.appendingPathComponent("debug.log")
    let line = "\(ISO8601DateFormatter().string(from: Date())) \(msg)\n"
    if let h = try? FileHandle(forWritingTo: url) { h.seekToEndOfFile(); h.write(Data(line.utf8)); try? h.close() }
    else { try? line.write(to: url, atomically: true, encoding: .utf8) }
}

enum Permissions {
    static var accessibilityTrusted: Bool { AXIsProcessTrusted() }

    static func requestAccessibility() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }
}
